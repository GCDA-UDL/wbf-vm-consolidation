#!/usr/bin/env python3
"""Aggregates fa_raw_v2.csv (written by fa_revision.py) into the Markdown and LaTeX tables.

  python -B forecast_accuracy/fa_tables.py [--raw forecast_accuracy/fa_raw_v2.csv]

Pooled over all windows of a workload (PlanetLab: over the daily traces present in the CSV).
Errors are in percentage points of VM CPU utilisation.  bias = mean(prediction - actual).
"""
import argparse
import collections
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--raw", default=os.path.join(HERE, "fa_raw_v2.csv"))
a = ap.parse_args()

acc = collections.defaultdict(lambda: dict(n=0, se=0.0, sa=0.0, sq=0.0, nm=0, sape=0.0, fb=0, vms=set(), traces=set()))
for r in csv.DictReader(open(a.raw, newline="", encoding="utf-8")):
    k = (r["workload"], r["protocol"], r["signal"], r["forecaster"])
    x = acc[k]
    x["n"] += int(r["n"])
    x["se"] += float(r["sum_err"])
    x["sa"] += float(r["sum_abs"])
    x["sq"] += float(r["sum_sq"])
    x["nm"] += int(r["n_mape"])
    x["sape"] += float(r["sum_ape"])
    x["fb"] += int(r["fallbacks"])
    x["vms"].add((r["trace"], r["vm"]))
    x["traces"].add(r["trace"])


def m(k):
    x = acc.get(k)
    if not x or not x["n"]:
        return None
    return dict(n=x["n"], bias=x["se"] / x["n"], mae=x["sa"] / x["n"], rmse=(x["sq"] / x["n"]) ** 0.5,
                mape=(100.0 * x["sape"] / x["nm"]) if x["nm"] else float("nan"), fb=x["fb"],
                vms=len(x["vms"]), traces=len(x["traces"]))


WLS = ["PlanetLab", "Alibaba", "Materna", "Azure"]
FCS = ["Prophet", "LVP", "EWMA0.8", "EWMA0.5"]
EXPECT = {"PlanetLab": 1000, "Alibaba": 100, "Materna": 100, "Azure": 100}
BLOCKS = [("A", "raw", "Protocol A: one step ahead at every step, window of 30 samples, raw series"),
          ("B", "raw", "Protocol B: at each decision instant (every 6 steps), window of the last min(t, 30) samples, "
                       "mean of the 6-step forecast against the mean of the next 6 observed samples, raw series"),
          ("B", "bollinger", "Protocol B with the Bollinger-transformed window (upper band, N = 5, alpha = 0.5) as "
                             "input and the same raw target: what WBP gives to the forecaster")]
md = ["# Forecast accuracy on the series the simulator reads (new analysis)", "",
      "Per-VM CPU series, first 288 samples, columns as read by the simulator (Alibaba: `cpu_util_percent`; "
      "Azure: `avg`; Materna: `CPU usage [%]`; PlanetLab: the daily files). Errors in percentage points of VM CPU "
      "utilisation, pooled over all windows. bias = mean(prediction − actual). MAPE excludes targets below 1 %, "
      "as the submitted script did. `fallbacks`: Prophet calls that raised ValueError and returned the last value. "
      "EWMA0.8 = exponential smoothing as the simulator runs it (statsmodels, level 0.8, last value under 10 "
      "samples); EWMA0.5 = the pandas EWMA of the submitted table.", "",
      "The consolidation loop forecasts host-level utilisation (sum of the VMs on a host), which only exists "
      "inside a simulation; these are per-VM series.", ""]
for proto, signal, title in BLOCKS:
    md += [f"## {title}", "",
           "| workload | VMs (expected) | forecaster | n | bias | MAE | RMSE | MAPE (%) | fallbacks |",
           "|---|---|---|---|---|---|---|---|---|"]
    for wl in WLS:
        for fc in FCS:
            g = m((wl, proto, signal, fc))
            if g:
                md.append(f"| {wl} | {g['vms']} ({EXPECT[wl]}{'' if proto == 'B' else '; A: PlanetLab day 20110303 = 100'}) | {fc} | {g['n']} | {g['bias']:+.2f} | "
                          f"{g['mae']:.2f} | {g['rmse']:.2f} | {g['mape']:.1f} | {g['fb']} |")
    md.append("")
open(os.path.join(HERE, "forecast_accuracy.md"), "w", encoding="utf-8").write("\n".join(md) + "\n")

# LaTeX: Prophet, LVP, EWMA(0.8)
tex = ["% Generated by experiments/forecast_accuracy/fa_tables.py -- do not edit by hand.",
       r"\begin{table*}[!ht]", r"\centering",
       r"\caption{Forecast accuracy on the per-VM CPU series read by the simulator (first 288 samples), in "
       r"percentage points of CPU utilization. A: one step ahead at every step with a 30-sample window. B: as the "
       r"method uses the forecast, i.e.\ at each decision instant (every 6 steps), window of the last "
       r"$\min(t,30)$ samples, mean of the 6-step forecast against the mean of the next 6 observations. "
       r"B+BB: protocol B with the Bollinger upper band ($N=5$, $\alpha=0.5$) of the window as input and the same "
       r"target, which is the series \textit{WBP} passes to the forecaster; bias is the mean of prediction minus "
       r"observation. EWMA: exponential smoothing with level 0.8, as in the closed-loop runs. For PlanetLab, A uses "
       r"the day 20110303 and B the ten days; $n_A$ and $n_B$ are the numbers of forecasts evaluated.}",
       r"\label{tab:forecast_val_u}",
       r"\begin{adjustbox}{width=0.85\textwidth}",
       r"\begin{tabular}{llrrrrrrr}", r"\hline",
       r" & & \multicolumn{2}{c}{A (1 step)} & \multicolumn{2}{c}{B (6-step mean)} & \multicolumn{3}{c}{B+BB} \\",
       r"\textbf{Workload} & \textbf{Forecaster} & MAE & RMSE & MAE & RMSE & Bias & MAE & RMSE \\", r"\hline"]


def f2(g, key):
    return "--" if g is None else (f"{g[key]:+.2f}" if key == "bias" else f"{g[key]:.2f}")


for wl in WLS:
    gB = m((wl, "B", "raw", "Prophet"))
    gA = m((wl, "A", "raw", "Prophet"))
    nA = gA["n"] if gA else 0
    nB = gB["n"] if gB else 0
    sA = f"{nA:,}".replace(",", r"\,")
    sB = f"{nB:,}".replace(",", r"\,")
    tex.append(f"\\multicolumn{{9}}{{l}}{{\\textbf{{{'Microsoft Azure' if wl == 'Azure' else wl}}} "
               f"($n_A={sA}$, $n_B={sB}$)}} \\\\")
    for fc, lab in [("Prophet", "Prophet"), ("LVP", "LVP"), ("EWMA0.8", "EWMA")]:
        ga, gb, gbb = m((wl, "A", "raw", fc)), m((wl, "B", "raw", fc)), m((wl, "B", "bollinger", fc))
        tex.append(f" & {lab} & {f2(ga, 'mae')} & {f2(ga, 'rmse')} & {f2(gb, 'mae')} & {f2(gb, 'rmse')} & "
                   f"{f2(gbb, 'bias')} & {f2(gbb, 'mae')} & {f2(gbb, 'rmse')} \\\\")
    tex.append(r"\hline")
tex += [r"\end{tabular}", r"\end{adjustbox}", r"\end{table*}"]
open(os.path.join(HERE, "tab_forecast_accuracy.tex"), "w", encoding="utf-8", newline="\n").write("\n".join(tex) + "\n")
print("\n".join(md[4:]))
