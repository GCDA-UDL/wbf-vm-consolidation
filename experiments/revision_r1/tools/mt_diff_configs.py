#!/usr/bin/env python3
"""Diff proof for the configs of the robustness check (runs `mt_*`).  Read-only on the configs;
writes tables/mt_config_diff.md; exit code 1 on any violation.

  python -B tools/mt_diff_configs.py

A. Base configs mt_<trace>_<family>.json against their template (the paper's config of the same
   provider and family): the differing fields must be exactly name, experimentOutputFolder and
   workloadTrace; key order identical.
B. Single-run configs mt_<trace>__<tag>_sNN.json (1 200):
   B1 against the template single, derived here INDEPENDENTLY of make_singles.py: the paper config of
      the same provider with the seed and the technique fixed exactly as the November tooling fixed
      them.  Differing fields must be exactly name, experimentOutputFolder and workloadTrace.
   B2 against every single-run config of the November campaign with the same provider, technique and
      seed (cl_<p>__lvp/wp/wbp, t0_static__*, h2_<p>__mmt/mc), when it exists: same rule.
   B3 every array has one element (one simulation per file), the seed matches the name, and the
      fields that define the technique are those of the paper (table printed below).
C. Lists: every name has a config, no duplicates, sizes, the four campaign lists cover the 1 200
   singles exactly once, smoke lists are subsets.
"""
import copy
import glob
import json
import os
import sys
from collections import Counter, defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mt_common as M  # noqa: E402

OUT = os.path.join(M.EXP, "tables", "mt_config_diff.md")
MISSING = object()
BAD = []


def load(name):
    with open(os.path.join(M.TESTBED, name + ".json"), encoding="utf-8") as fh:
        return json.load(fh)


def exists(name):
    return os.path.exists(os.path.join(M.TESTBED, name + ".json"))


def diff(a, b):
    return {k for k in set(a) | set(b) if a.get(k, MISSING) != b.get(k, MISSING)}


def derive(tpl, seed, sets):
    """Template single: the paper config with the seed and the technique fixed (as make_singles.py does,
    re-implemented here so that the proof does not rely on the generator)."""
    d = copy.deepcopy(tpl)
    d["override"] = []
    d["randomSeed"] = [seed]
    for k, v in sets.items():
        d[k] = [v]
    return d


SIG_KEYS = ["selectionPolicy", "hostForecastingTechnique", "hostSignalProcessing", "hostOverSaturationPolicy",
            "vmMigrationPolicy", "parameter", "vmForecastingTechniqueBasic", "vms", "dataStartStep", "numCloudlets",
            "workloadTrace"]
md = ["# Configs of the robustness check: diff against their templates", "",
      "Generated by `tools/mt_diff_configs.py`. Allowed differences (run identification and workload folder): "
      "`name`, `experimentOutputFolder`, `workloadTrace`. `dataStartStep` is not changed (0 in every config).", ""]

# A. base configs -----------------------------------------------------------------------------------
md += ["## A. Base configs against the paper's configs", "",
       "| new config | template | differing fields | new workloadTrace | key order identical |", "|---|---|---|---|---|"]
fams = sorted({t[2] for t in M.TECHS})
for tr in M.TRACES:
    for fam in fams:
        tpl_n, new_n = M.template_name(tr["provider"], fam), M.base_name(tr, fam)
        tpl, new = load(tpl_n), load(new_n)
        dk = diff(tpl, new)
        ok = dk == M.ALLOWED_DIFF and new["workloadTrace"] == [M.workload_trace(tr)] \
            and tpl["workloadTrace"] == [f"{M.PROVIDERS[tr['provider']]['wtype']}/{M.PROVIDERS[tr['provider']]['sim']}"]
        if not ok:
            BAD.append(f"A {new_n}: {sorted(dk)}")
        md.append(f"| `{new_n}` | `{tpl_n}` | {', '.join(sorted(dk))} | `{new['workloadTrace'][0]}` | {list(tpl) == list(new)} |")
md.append("")

# B. singles -----------------------------------------------------------------------------------------
cnt = Counter()
nov_used = Counter()
sig = {}
md_b2 = []
for tr in M.TRACES:
    prov = tr["provider"]
    for tag, label, fam, sets, _ in M.TECHS:
        tpl = load(M.template_name(prov, fam))
        for s in M.SEEDS:
            name = M.single_name(tr, tag, s)
            d = load(name)
            # B1
            dk = diff(derive(tpl, s, sets), d)
            cnt["B1 checked"] += 1
            if dk == M.ALLOWED_DIFF:
                cnt["B1 ok"] += 1
            else:
                BAD.append(f"B1 {name}: {sorted(dk)}")
            # B2
            for pat in M.NOVEMBER[tag]:
                nov = pat.format(p=prov, s=s)
                if not exists(nov):
                    continue
                nd = load(nov)
                if nd["workloadTrace"] != [f"{M.PROVIDERS[prov]['wtype']}/{M.PROVIDERS[prov]['sim']}"]:
                    continue                    # e.g. t0_static__* is Materna only
                dk2 = diff(nd, d)
                cnt["B2 checked"] += 1
                nov_used[(prov, tag, pat.split("_s{")[0].replace("{p}", prov))] += 1
                if dk2 == M.ALLOWED_DIFF:
                    cnt["B2 ok"] += 1
                else:
                    BAD.append(f"B2 {name} vs {nov}: {sorted(dk2)}")
            # B3
            multi = [k for k, v in d.items() if k != "override" and isinstance(v, list) and len(v) != 1]
            if multi or d["randomSeed"] != [s] or d["name"] != [name] or d["experimentOutputFolder"] != [tr["exp"]] \
                    or d["workloadTrace"] != [M.workload_trace(tr)]:
                BAD.append(f"B3 {name}: swept {multi} or identification fields wrong")
            else:
                cnt["B3 ok"] += 1
            sig.setdefault((prov, label), set()).add(json.dumps({k: d[k][0] for k in SIG_KEYS if k != "workloadTrace"}))

md += ["## B. Single-run configs (1 200)", "",
       f"- B1, against the template single derived from the paper config: {cnt['B1 ok']} of {cnt['B1 checked']} "
       "differ exactly in `name`, `experimentOutputFolder`, `workloadTrace`.",
       f"- B2, against the November single-run config with the same provider, technique and seed: {cnt['B2 ok']} of "
       f"{cnt['B2 checked']} comparisons differ exactly in those three fields.",
       f"- B3, one value per field, seed and identification fields consistent with the name: {cnt['B3 ok']} of 1200.", "",
       "November configs used in B2 (provider, technique, November family: number of seeds compared):", "",
       "| provider | technique | November configs | seeds |", "|---|---|---|---|"]
for (prov, tag, fam_), n in sorted(nov_used.items()):
    md.append(f"| {prov} | {M.TECH_BY_TAG[tag][1]} | `{fam_}_sNN` | {n // sum(1 for t in M.TRACES if t['provider'] == prov)} |")
md += ["", "Fields that define the technique, as found in the 30 x 2 singles of each provider and technique "
       "(one distinct combination expected per row):", "",
       "| provider | technique | " + " | ".join(k for k in SIG_KEYS if k != "workloadTrace") + " |",
       "|---|---|" + "---|" * (len(SIG_KEYS) - 1)]
for (prov, label), ss in sorted(sig.items(), key=lambda x: (x[0][0], [t[1] for t in M.TECHS].index(x[0][1]))):
    if len(ss) != 1:
        BAD.append(f"B3 {prov}/{label}: {len(ss)} distinct technique signatures")
    v = json.loads(next(iter(ss)))
    md.append(f"| {prov} | {label} | " + " | ".join(f"`{json.dumps(v[k])}`" for k in SIG_KEYS if k != "workloadTrace") + " |")
md.append("")

# C. lists -------------------------------------------------------------------------------------------
md += ["## C. Run lists", "", "| list | runs | distinct | configs missing | techniques |", "|---|---|---|---|---|"]
all_singles = {M.single_name(tr, t[0], s) for tr in M.TRACES for t in M.TECHS for s in M.SEEDS}
on_disk = {os.path.basename(p)[:-5] for p in glob.glob(os.path.join(M.TESTBED, "mt_*__*.json"))}
covered = Counter()
expected_sizes = {M.LIST_FILES["fast"]: 600, M.LIST_FILES["prophet"]: 240, M.LIST_FILES["sota"]: 240,
                  M.LIST_FILES["neural"]: 120, M.SMOKE_FILE: 36, M.SMOKE_NEURAL_FILE: 4}
for fn, size in expected_sizes.items():
    with open(os.path.join(M.LISTS, fn), encoding="utf-8") as fh:
        names = [ln.strip() for ln in fh if ln.strip()]
    miss = [n for n in names if n not in on_disk]
    techs = Counter(M.TECH_BY_TAG[n.split("__")[1].rsplit("_s", 1)[0]][1] for n in names)
    if len(names) != size or len(set(names)) != len(names) or miss:
        BAD.append(f"C {fn}: {len(names)} runs, {len(set(names))} distinct, {len(miss)} without config")
    if fn not in (M.SMOKE_FILE, M.SMOKE_NEURAL_FILE):
        covered.update(names)
    md.append(f"| `lists/{fn}` | {len(names)} | {len(set(names))} | {len(miss)} | "
              + ", ".join(f"{k} {v}" for k, v in techs.items()) + " |")
ok_cov = set(covered) == all_singles and all(v == 1 for v in covered.values()) and on_disk == all_singles
if not ok_cov:
    BAD.append("C: the four campaign lists do not cover the 1 200 singles exactly once")
md += ["", f"The four campaign lists cover the {len(all_singles)} single-run configs exactly once: {ok_cov}; "
       f"`mt_*__*.json` files in `testbed`: {len(on_disk)}.", "",
       f"Result: {'all checks passed' if not BAD else str(len(BAD)) + ' violation(s)'}."]
md += [f"- {b}" for b in BAD[:50]]
with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(md) + "\n")
print("\n".join(md))
print(f"\nwritten {OUT}")
sys.exit(1 if BAD else 0)
