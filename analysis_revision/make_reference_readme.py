#!/usr/bin/env python3
"""Writes results/reference/README.md from results/reference/facts.json.

facts.json is produced by build_revision.py (same folder) from the raw simulation outputs, so the
reference tables of the package are the tables of the revised manuscript by construction.

Usage (from analysis_revision/):
  python -B make_reference_readme.py [--facts ../results/reference/facts.json]
                                     [--out ../results/reference/README.md]
"""
import argparse
import json
import os

import revlib as L

HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("--facts", default=os.path.join(HERE, "..", "results", "reference", "facts.json"))
ap.add_argument("--out", default=os.path.join(HERE, "..", "results", "reference", "README.md"))
a = ap.parse_args()
F = json.load(open(a.facts, encoding="utf-8"))
A = F["agg"]

WLNAME = {"planetlab": "PlanetLab", "alibaba": "Alibaba", "materna": "Materna", "azure": "Microsoft Azure"}
MAIN = ["MU", "MMT", "RS", "MC", "WPSP", "WP", "WBP"]
SOTA = ["WBP", "BB+NeoPro", "AMOVMC", "EUQ-VMC"]
ROWS = [  # key, label, decimals
    ("e_hosts", "Host energy (kWh)", 2),
    ("e_mig", "Migration energy (kWh)", 2),
    ("e_total", "Total energy (kWh)", 2),
    ("act_hosts", "Mean active hosts", 2),
    ("sla", "SLA violation (%)", 2),
    ("migr", "# of migrations", 0),
    ("traffic", "Migration traffic (GB·hop)", 0),
    ("me", "ME ratio (×10^7)", 2),
    ("avmips", "Avg. available MIPS/active host", 0),
    ("vmcomm", "Inter-VM link load (×10^5)", 2),
]


def cell(wl, t, key, d):
    g = A[wl][t][key]
    return f"{g['mean']:.{d}f} ± {g['ci']:.{d}f}"


def table(wl, techs):
    out = ["| Metric | " + " | ".join(techs) + " |", "|---|" + "---:|" * len(techs)]
    for key, label, d in ROWS:
        out.append(f"| {label} | " + " | ".join(cell(wl, t, key, d) for t in techs) + " |")
    return out


md = []
w = md.append
w("# Reference results of the revised manuscript")
w("")
w("Generated by `analysis_revision/make_reference_readme.py` from `facts.json` (same folder). Do not edit")
w("by hand: regenerate. `facts.json` is written by `analysis_revision/build_revision.py` from the raw")
w("simulation outputs, with the same code that writes the tables of the manuscript, so these tables and")
w("those of the manuscript cannot differ.")
w("")
w("## What the values are")
w("")
w(f"- Means and 95% confidence intervals of the {F['totals']['all']} simulations behind the tables of the")
w(f"  revised manuscript ({F['totals']['main']} for the seven techniques of the per-workload tables).")
w("- PlanetLab: ten daily traces × 30 seeds per technique; the confidence interval is computed over the")
w("  ten daily means, because runs of the same day share the trace. Alibaba, Materna and Microsoft Azure:")
w("  one trace × 30 seeds; the interval is computed over the 30 seeds.")
w("- The tables of the three experiments added by the revision (closed-loop replacement of the forecaster,")
w("  sensitivity to the Bollinger parameters, forecast accuracy) are in `experiments/revision_r1/tables/`.")
w("")
w("## Definitions")
w("")
w("- **Host energy**: energy of the active hosts plus host start-up and shutdown.")
w(f"- **Migration energy**: sum over the migrations of `kappa × hops × MB + beta`, with kappa = {F['kappa']} J per MB")
w(f"  and hop and beta = {F['beta']} J per migration. `MB` is the memory of the migrated VM and `hops` the number of")
w("  links of the shortest path between source and destination hosts. The two coefficients are those of the model")
w("  of Liu et al. (HPDC 2011, Eq. 17: E = 0.512·V + 20.165, with V in megabytes and E in joules). No coefficient")
w("  was measured by the authors.")
w("- **Total energy**: host energy plus migration energy.")
w("- **Migration traffic**: memory moved by the migrations weighted by the hops of each path, in GB·hop. Each")
w("  migration is counted once. The simulator registers every migration twice in its network accounting")
w("  (`totalRAMInBW`), so the scripts halve that field.")
w("- **Mean active hosts**: active hosts averaged over the 288 samples of a simulated day.")
w("- **ME ratio**: executed MIPS per kWh of total energy (higher is better).")
w("- **Inter-VM link load**: bandwidth occupied by the communications between VMs, accumulated over links and")
w("  samples (lower means communicating VMs are placed closer).")
w("")
w("The tables of the submitted version (24 September 2026) used a different energy expression: migration traffic")
w("as registered by the simulator (every migration counted twice), 4.096 J per MB and a 1.1 factor. 4.096 is eight")
w("times the coefficient of the model; it is not a measurement. Files that still carry those values are marked as")
w("such.")
w("")
w("## Comparing a re-execution with these tables")
w("")
w("Compare aggregates (mean and confidence interval per technique and workload), not individual runs.")
w("")
w("- Individual runs are not reproducible bit for bit, for any of the techniques. At several points of a decision")
w("  the implementation chooses among equivalent candidates (hosts of equal capacity, VMs with the same heuristic")
w("  value, the order in which overloaded hosts are processed), and it resolves those ties by the iteration order")
w("  of hash-based collections, which depends on the state of the Java runtime and not only on the seed. The")
w("  results are therefore distributions over seeds and traces.")
w("- The runs of WPSP, WP and WBP were executed again (13 traces × 3 techniques × 30 seeds = 1,170 runs, one")
w("  simulation per JVM) and the means of the two campaigns agree: one of the 60 paired comparisons (three")
w("  techniques, four workloads, five metrics) has p < 0.05 before correction for multiple tests. The comparison is")
w("  in `experiments/revision_r1/tables/rerun_vs_stored.md`.")
w("- The runs of the other techniques have not been executed again.")
w("")
w("## Simulations behind each table")
w("")
w("| Technique | PlanetLab (traces × seeds) | Alibaba | Materna | Azure | Runs | Experiment configs (`testbed/`) |")
w("|---|---|---|---|---|---:|---|")
CFG = {
    "classical": "`pl_static_<day>`, `paper4_full_<workload>_static`",
    "prophet": "`p4_pl_<day>_st`, `paper4_full_<workload>_prophet_st`",
    "np": "`np_pl_<day>_st`, `np_<workload>_st`",
    "amovmc": "`amovmc_pl_<day>`, `amovmc_<workload>`",
    "euqvmc": "`euqvmc_pl_<day>`, `euqvmc_<workload>`",
}
GROUP = {"MU": "classical", "MMT": "classical", "RS": "classical", "MC": "classical", "WPSP": "classical",
         "WP": "prophet", "WBP": "prophet", "BB+NeoPro": "np", "AMOVMC": "amovmc", "EUQ-VMC": "euqvmc"}
# consistency of the config names with the folder map used by the analysis
tf = L.table_folders("planetlab")
assert tf["static"][0].startswith("pl_static_") and tf["prophet"][0].startswith("p4_pl_") and \
    tf["prophet"][0].endswith("_st") and tf["np"][0].startswith("np_pl_"), "folder map changed: update CFG"
tfa = L.table_folders("alibaba")
assert tfa["static"] == ["paper4_full_alibaba_static"] and tfa["prophet"] == ["paper4_full_alibaba_prophet_st"]
for t in L.ALL_T:
    cells = []
    n = 0
    for wl in L.WLS:
        i = F["inventory"][f"{wl}/{t}"]
        cells.append(f"{i['traces']} × {i['seeds']}")
        n += i["n"]
    w(f"| {t} | " + " | ".join(cells) + f" | {n} | {CFG[GROUP[t]]} |")
w("")
w("`<day>` is one of the ten PlanetLab days (" + ", ".join(L.DAYS) + "). In the two Prophet configs each seed runs")
w("WP (no Bollinger step) and WBP (Bollinger step). Config and folder names keep the labels used when the package")
w("was created (`WF` = WP, `WBF` = WBP).")
w("")
for wl in L.WLS:
    w(f"## {WLNAME[wl]}")
    w("")
    md.extend(table(wl, MAIN))
    w("")
w("## Comparison with recent methods (shared placement stage)")
w("")
w("AMOVMC and EUQ-VMC are re-implemented in the simulator of this package (detection and selection stages) and")
w("use the same placement stage as WBP. The original articles do not report a value for gamma (overload test of")
w("AMOVMC) or for the safety factor `safe` (EUQ-VMC): gamma = 0.80 and safe = 1.5 were set by the authors of this")
w("package. The re-implementation of AMOVMC is partial (its neural predictor is not implemented, among other")
w("differences listed in `SOTA_COMPARISON.md`). BB+NeoPro is the WBP loop with the NeuralProphet forecaster, not")
w("the 2023 method as published.")
w("")
for wl in L.WLS:
    w(f"### {WLNAME[wl]}")
    w("")
    md.extend(table(wl, SOTA))
    w("")
w("## AMOVMC and EUQ-VMC with the shared and with their own placement stage (means)")
w("")
w("E×SLA is total energy (kWh) times SLA violation (%). Configs of the native placement: `amovmc_native_*`,")
w("`euqvmc_native_*`. The native placement of AMOVMC uses equal weights (1/6) for the six terms of its fitness")
w("function, whereas the AMOVMC article reports its own weights in its Table 3 (−10, 13, 6, −2.5, −0.25, −0.25).")
w("The native placement of EUQ-VMC is a greedy placement on a weighted sum of its three objectives; its MOFPA/D")
w("search is not implemented. Confidence intervals are in the corresponding table of the manuscript.")
w("")
w("| Workload | Method | Total energy (kWh) | SLA (%) | # migr. | Traffic (GB·hop) | E×SLA |")
w("|---|---|---:|---:|---:|---:|---:|")
for wl in L.WLS:
    for lab, v in F["native"][wl].items():
        name = "WBP" if "WBP" in lab else lab
        w(f"| {WLNAME[wl]} | {name} | {v['e_total']:.2f} | {v['sla']:.2f} | {v['migr']:.0f} | {v['traffic']:.0f} | "
          f"{v['esv']:.1f} |")
w("")
w(f"## Parameter sweeps of AMOVMC and EUQ-VMC (PlanetLab day {F['tune_day']}, 30 seeds, shared placement, means)")
w("")
w("The settings of the comparison table (gamma = 0.80, safe = 1.5) were chosen by the authors of this package; the")
w("original articles do not report these values.")
w("")
w("| Method (setting) | Total energy (kWh) | SLA (%) | # migr. | Traffic (GB·hop) | E×SLA |")
w("|---|---:|---:|---:|---:|---:|")


def trow(label, v):
    w(f"| {label} | {v['e_total']:.2f} | {v['sla']:.2f} | {v['migr']:.0f} | {v['traffic']:.0f} | {v['esv']:.1f} |")


trow("WBP", F["tune_ref"]["WBP"])
trow("AMOVMC (gamma = 0.80, setting of the comparison table)", F["tune_ref"]["AMOVMC"])
for f in sorted(F["tune"]):
    if f.startswith("amovmc_tune_"):
        trow(f"AMOVMC (gamma = {float(F['tune'][f]['parameter']):.2f}; `{f}`)", F["tune"][f])
trow("EUQ-VMC (safe = 1.50, setting of the comparison table)", F["tune_ref"]["EUQ-VMC"])
for f in sorted(F["tune"], reverse=True):
    if f.startswith("euqvmc_tune_"):
        trow(f"EUQ-VMC (safe = {float(F['tune'][f]['parameter']):.2f}; `{f}`)", F["tune"][f])
w("")
w("## Sensitivity of the total-energy comparison to kappa")
w("")
w("Saving in total energy of WBP with respect to the classical techniques (MU, MMT, RS, MC), in %: range over the")
w("four techniques. Negative: WBP consumes more.")
w("")
w("0.512 J per MB and hop is the reference coefficient (model of Liu et al.). 3.549 J per MB is the value measured")
w("by Sarji et al. (2011), which is the constant built into the simulator. 4.096 J per MB is the value used in the")
w("submitted version: eight times the reference, not a measurement.")
w("")
w("| kappa (J per MB and hop) | PlanetLab | Alibaba | Materna | Azure |")
w("|---|---|---|---|---|")
KLAB = [(0.0, "0 (host energy only)"), (L.KAPPA_REF, "0.512 (reference)"),
        (L.KAPPA_SIMULATOR, "3.549 (Sarji et al.)"), (L.KAPPA_SUBMITTED, "4.096 (submitted version)")]


def klabel(kp):
    for v, lab in KLAB:
        if abs(float(kp) - v) < 1e-9:
            return lab
    return f"{float(kp):g}"


for kp in [k for k in F["sens"]["planetlab"] if k != "breakeven"]:
    w(f"| {klabel(kp)} | " + " | ".join(
        f"{F['sens'][wl][kp]['lo']:.1f} to {F['sens'][wl][kp]['hi']:.1f}" for wl in L.WLS) + " |")
w("| WBP below at least one classical technique from | " + " | ".join(
    f"{max(0.0, min(F['sens'][wl]['breakeven'].values())):.2f}" for wl in L.WLS) + " |")
w("| WBP below the four classical techniques from | " + " | ".join(
    f"{max(0.0, max(F['sens'][wl]['breakeven'].values())):.2f}" for wl in L.WLS) + " |")
w("")
w("## Statistical tests")
w("")
w(f"`stats.md` (same folder) lists the {F['n_tests']} paired tests of WBP against each of the other nine techniques on")
w("the ten metrics and the four workloads, with raw and Holm-adjusted p-values. PlanetLab: paired t-test on the ten")
w("daily means. Other workloads: Wilcoxon signed-rank test on the 30 seed-paired runs.")
w("")
w("## How to regenerate")
w("")
w("See `analysis_revision/README.md`: extract the per-run cache from `output/`, run `build_revision.py`, copy")
w("`facts.json` and `stats.md` here and run this script.")

with open(a.out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(md) + "\n")
print(f"written {a.out}: {len(md)} lines")
